"""Generate a firmware version without changing configuration or OTA identities."""
from datetime import datetime, timezone
from pathlib import Path
import os
import subprocess

Import('env')

root = Path(env.subst('$PROJECT_DIR')).resolve()
release_date = os.environ.get('RELEASE_TAG') or datetime.now(timezone.utc).strftime('%Y%m%d')
if len(release_date) != 8 or not release_date.isascii() or not release_date.isdigit():
    raise ValueError('RELEASE_TAG must be a YYYYMMDD date')
datetime.strptime(release_date, '%Y%m%d')


def git(*args):
    return subprocess.check_output(['git', *args], cwd=root, stderr=subprocess.DEVNULL,
                                   text=True).strip()


try:
    # A source archive inside another checkout must not inherit that parent's SHA.
    if Path(git('rev-parse', '--show-toplevel')).resolve() != root:
        raise ValueError('No project checkout')
    revision = git('rev-parse', 'HEAD')[:7]
    dirty = bool(git('status', '--porcelain', '--untracked-files=normal'))
    version = release_date + '-' + revision + ('-dirty' if dirty else '')
except (OSError, subprocess.CalledProcessError, ValueError):
    version = release_date + '-dev'

generated = Path(env.subst('$BUILD_DIR')) / 'generated'
generated.mkdir(parents=True, exist_ok=True)
header = generated / 'FirmwareVersion.h'
content = '// Generated by scripts/build-version.py.\n#pragma once\n#define FIRMWARE_VERSION "' + version + '"\n'
if not header.exists() or header.read_text() != content:
    header.write_text(content)
env.Append(CPPPATH=[str(generated)])
print('Firmware version: ' + version)
