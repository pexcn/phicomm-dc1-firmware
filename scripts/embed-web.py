"""Embed local web assets in flash; no filesystem image or frontend packages."""
from pathlib import Path
import gzip

Import('env')

root = Path(env.subst('$PROJECT_DIR'))
generated = Path(env.subst('$BUILD_DIR')) / 'generated'
generated.mkdir(parents=True, exist_ok=True)
lines = ['// Generated by scripts/embed-web.py; edit web/ instead.',
         '#pragma once', '#include <Arduino.h>']
for name, filename in [('WebIndex', 'index.html'), ('WebStyle', 'style.css'),
                       ('WebScript', 'app.js')]:
    data = gzip.compress((root / 'web' / filename).read_bytes(), compresslevel=9, mtime=0)
    lines.append('static const uint8_t %s[] PROGMEM = {' % name)
    lines.extend(','.join('0x%02x' % byte for byte in data[i:i + 20]) + ','
                 for i in range(0, len(data), 20))
    lines.append('};')
header = generated / 'WebAssets.h'
content = '\n'.join(lines) + '\n'
if not header.exists() or header.read_text() != content:
    header.write_text(content)
env.Append(CPPPATH=[str(generated)])
